def _horizontal_detour_metrics(path: np.ndarray, config) -> dict:
    path_xy = np.asarray(path, np.float64).reshape(-1, 3)[:, :2]
    start = np.asarray(config.taskspace.start[:2], np.float64)
    goal = np.asarray(config.taskspace.goal[:2], np.float64)
    direction = goal - start
    direct_distance = float(np.linalg.norm(direction))
    if direct_distance <= 0.0:
        raise ValueError("start and goal must be distinct")
    unit = direction / direct_distance
    transverse = np.asarray([-unit[1], unit[0]])
    signed_cross_track = (path_xy - start[None]) @ transverse
    path_length = float(np.linalg.norm(np.diff(path_xy, axis=0), axis=1).sum())
    endpoint_direct = float(np.linalg.norm(path_xy[-1] - path_xy[0]))
    return {
        "horizontal_transverse_rms_m": float(
            np.sqrt(np.mean(signed_cross_track ** 2))
        ),
        "horizontal_max_abs_cross_track_m": float(
            np.max(np.abs(signed_cross_track))
        ),
        "horizontal_path_length_m": path_length,
        "horizontal_path_inefficiency_m": path_length - endpoint_direct,
        "mean_signed_cross_track_m": float(np.mean(signed_cross_track)),
    }


def _draw_spheres(axis, spheres: np.ndarray, physical_radius: float):
    azimuth = np.linspace(0.0, 2.0 * np.pi, 32)
    polar = np.linspace(0.0, np.pi, 18)
    unit_x = np.outer(np.cos(azimuth), np.sin(polar))
    unit_y = np.outer(np.sin(azimuth), np.sin(polar))
    unit_z = np.outer(np.ones_like(azimuth), np.cos(polar))
    for x, y, z, modeled_radius in np.asarray(spheres, np.float64).reshape(-1, 4):
        axis.plot_wireframe(
            x + modeled_radius * unit_x,
            y + modeled_radius * unit_y,
            z + modeled_radius * unit_z,
            color="#2b8cbe",
            alpha=0.32,
            linewidth=0.5,
        )
        axis.plot_surface(
            x + physical_radius * unit_x,
            y + physical_radius * unit_y,
            z + physical_radius * unit_z,
            color="#747b80",
            alpha=0.66,
            linewidth=0.0,
            shade=True,
        )


